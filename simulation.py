def result_3_sweep_table(ages, s_star, N_star, beta_star):
    print("=== Result 3: sensitivity sweep ===")
    factors = [0.5, 0.95, 0.99, 1.01, 1.05, 2.0]
    rows    = []

    print(f"  {'factor':>7}  {'beta':>9}  {'R_0':>9}  {'final I_h':>12}  {'prev':>9}  {'outcome':>9}  {'time':>6}")
    print(f"  {'-'*7}  {'-'*9}  {'-'*9}  {'-'*12}  {'-'*9}  {'-'*9}  {'-'*6}")

    for factor in factors:
        beta_used = factor * beta_star
        R_used    = R0(beta_used, ages, s_star, N_star)

        model  = KawakamiMalaria(beta=beta_used, i_init_frac=EPSILON)
        solver = AgeStructuredSolver(model, A_max=A_MAX, M=M)
        t0 = time.perf_counter()
        solver.run(T=T_LONG)
        elapsed = time.perf_counter() - t0

        N_h = float(trapezoid(solver.u[0] + solver.u[1] + solver.u[2], x=solver.ages))
        I_h = float(trapezoid(solver.u[1], x=solver.ages))
        prev = I_h / N_h
        outcome = 'persist' if prev > 1e-4 else 'die-off'

        print(f"  {factor:>7.2f}  {beta_used:>9.4f}  {R_used:>9.5f}  "
              f"{I_h:>12.3e}  {prev*100:>8.4f}%  {outcome:>9}  {elapsed:>5.1f}s")
        rows.append((factor, beta_used, R_used, I_h, prev, outcome, elapsed))
    print()
    return rows


