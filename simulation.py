# ---------------------------------------------------------------------
def result_2_threshold_figure(ages, s_star, N_star):
    print("=== Result 2: threshold figure ===")
    beta_star = beta_critical(ages, s_star, N_star)
    print(f"  beta* = {beta_star:.4f}    (from formula)")

    factors = [0.99, 1.01]
    histories = {}

    for factor in factors:
        beta_used = factor * beta_star
        R_used    = R0(beta_used, ages, s_star, N_star)
        print(f"  running beta = {factor}*beta* = {beta_used:.4f}, R_0 = {R_used:.5f}")

        model  = KawakamiMalaria(beta=beta_used, i_init_frac=EPSILON)
        solver = AgeStructuredSolver(model, A_max=A_MAX, M=M)

        sample_every = int(round(0.5 / solver.dt))    # half-yearly samples
        ts, Ihs = [], []
        n_steps = int(round(T_LONG / solver.dt))
        t0 = time.perf_counter()
        for k in range(n_steps):
            solver.step()
            if (k + 1) % sample_every == 0:
                ts .append(solver.t)
                Ihs.append(trapezoid(solver.u[1], x=solver.ages))
        elapsed = time.perf_counter() - t0
        histories[factor] = (np.array(ts), np.array(Ihs), R_used, elapsed)
        print(f"    finished in {elapsed:.1f}s")

    # Figure
    fig, ax = plt.subplots(figsize=(7.0, 4.5))
    for factor, (ts, Ihs, R, _) in histories.items():
        label = (rf'$\beta = {factor}\,\beta^*$, $R_0 = {R:.3f}$')
        ax.plot(ts, Ihs, label=label, linewidth=1.5)
    ax.set_xlabel('time (years)')
    ax.set_ylabel(r'total infected hosts $I_h(t)$')
    ax.set_title(r'Threshold dichotomy near $R_0 = 1$')
    ax.legend(loc='upper right')
    ax.set_yscale('log')
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig('threshold_figure.pdf', bbox_inches='tight')
    fig.savefig('threshold_figure.png', dpi=150, bbox_inches='tight')
    print(f"  figure saved to threshold_figure.{{pdf,png}}")
    print()
    return beta_star


