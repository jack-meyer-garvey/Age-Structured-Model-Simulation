# Result 1: DFE verification
# ---------------------------------------------------------------------
def result_1_dfe_verification():
    print("=== Result 1: DFE verification ===")
    ages, s_star, N_star, S_v_star = compute_dfe(M=M, T_settle=300.0)

    # Analytical DFE: s*(a) = s*(0) exp(-int_0^a [mu_h0 + mu_h1 N*]).
    # Use the simulated N* in the exponent for a self-consistent comparison.
    cumint = np.concatenate(([0.0],
        np.cumsum(0.5 * (mu_h0(ages[:-1]) + mu_h0(ages[1:])) * np.diff(ages))))
    surv_analytic = np.exp(-cumint - MU_H1 * N_star * ages)
    s_star_analytic = s_star[0] * surv_analytic / surv_analytic[0]

    rel_err = np.max(np.abs(s_star - s_star_analytic)) / s_star[0]
    print(f"  N_h^*               = {N_star:.4e}")
    print(f"  S_v^*               = {S_v_star:.4e}")
    print(f"  max |s_sim - s_an|  = {rel_err:.2e} (relative to s*(0))")
    print()
    return ages, s_star, N_star, S_v_star


