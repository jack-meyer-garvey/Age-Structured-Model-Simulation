"""
Example: Gurtin-MacCamy model implemented via AgeStructuredModel.

Uses the smooth rates from Milner & Rabbiolo (1992) Section 5 and verifies
that the general solver achieves second-order convergence on the analytical
steady-state test.
"""
import numpy as np
from scipy.integrate import trapezoid


# --- Rate functions (Milner & Rabbiolo Section 5) -----------------------
def f_bump(x):
    x = np.asarray(x, dtype=float)
    out = np.zeros_like(x)
    m = x > 1e-12
    out[m] = np.exp(-((1.0 - x[m]) / x[m]) ** 2)
    return out

def mu_age(a):
    a   = np.asarray(a, dtype=float)
    out = np.full_like(a, 12.0)
    m   = (a >= 0) & (a <= 85)
    out[m] = 12.0 * f_bump(a[m] / 85.0)
    return out

def beta_shape(a):
    a   = np.asarray(a, dtype=float)
    out = np.zeros_like(a)
    m   = (a >= 15) & (a <= 45)
    out[m] = f_bump(1.0 - np.abs(a[m] - 30.0) / 15.0)
    return out

# Normalize beta so that the steady state phi(a) = b0 * exp(-int mu) is a fixed point.
_ages_ref = np.linspace(0.0, 200.0, 200_001)
_mu_ref   = mu_age(_ages_ref)
_cumint   = np.concatenate(([0.0],
    np.cumsum(0.5 * (_mu_ref[:-1] + _mu_ref[1:]) * np.diff(_ages_ref))))
_surv     = np.exp(-_cumint)
K_NORM    = trapezoid(beta_shape(_ages_ref) * _surv, x=_ages_ref)

def beta_age(a):    return beta_shape(a) / K_NORM
def survival(a):    return np.interp(a, _ages_ref, _surv)
def phi_steady(a):  return 1.0e5 * survival(a)


# --- The model, expressed in the framework -----------------------------
class GurtinMacCamy(AgeStructuredModel):
    """Scalar (d=1) age-structured model with age-dependent mortality
    and renewal boundary."""

    def reaction(self, t, ages, u, w):
        return -mu_age(ages) * u                       # shape (1, M)

    def birth_kernel(self, ages, u):
        return (beta_age(ages) * u).reshape(1, -1)     # shape (1, M)

    def initial_condition(self, ages):
        return phi_steady(ages).reshape(1, -1)         # shape (1, M)


# --- Convergence verification ------------------------------------------
def run_one(dt, T=10.0, A_max=100.0):
    M = int(round(A_max / dt)) + 1
    solver = AgeStructuredSolver(GurtinMacCamy(), A_max=A_max, M=M)
    phi_grid = phi_steady(solver.ages).reshape(1, -1)

    n_steps = int(round(T / solver.dt))
    max_err = 0.0
    for _ in range(n_steps):
        solver.step()
        err = float(np.max(np.abs(solver.u - phi_grid)))
        if err > max_err:
            max_err = err
    return max_err


