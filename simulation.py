import numpy as np
from scipy.integrate import simpson


class AgeStructuredModel:
    """Base class. Subclasses override reaction, birth_kernel,
    initial_condition. For q > 0, also override reaction_ode and initial_ode."""

    def reaction(self, t, ages, u, w):
        """Return f(t, a, u, w), shape (d, M)."""
        raise NotImplementedError

    def birth_kernel(self, ages, u):
        """Return B(a) u, shape (d, M). Integrated over ages to give u(t, 0)."""
        raise NotImplementedError

    def initial_condition(self, ages):
        """Return u_0(a), shape (d, M)."""
        raise NotImplementedError

    def reaction_ode(self, t, u, w):
        """Return g(t, u, w), shape (q,). Default: q = 0."""
        return np.zeros(0)

    def initial_ode(self):
        """Return w_0, shape (q,). Default: q = 0."""
        return np.zeros(0)


class AgeStructuredSolver:

    def __init__(self, model, A_max, M):
        self.model = model
        self.A_max = float(A_max)
        self.M     = int(M)

        self.ages = np.linspace(0.0, self.A_max, self.M)
        self.da   = self.ages[1] - self.ages[0]
        self.dt   = self.da

        u0 = np.asarray(model.initial_condition(self.ages), dtype=float)
        if u0.ndim == 1:
            u0 = u0.reshape(1, -1)
        self.u = u0.copy()
        self.d = self.u.shape[0]

        self.w = np.asarray(model.initial_ode(), dtype=float).copy()
        self.q = self.w.size

        self.t = 0.0

    def _reaction_substep(self, dt, t_start):
        u, w = self.u, self.w
        k1_u = self.model.reaction    (t_start, self.ages, u, w)
        k1_w = self.model.reaction_ode(t_start,            u, w)

        u_pred = u + dt * k1_u
        w_pred = w + dt * k1_w

        k2_u = self.model.reaction    (t_start + dt, self.ages, u_pred, w_pred)
        k2_w = self.model.reaction_ode(t_start + dt,            u_pred, w_pred)

        self.u = u + 0.5 * dt * (k1_u + k2_u)
        self.w = w + 0.5 * dt * (k1_w + k2_w)

    def _transport_substep(self):
        prev_u0      = self.u[:, 0].copy()
        self.u       = np.roll(self.u, 1, axis=1)
        self.u[:, 0] = prev_u0

    def _apply_boundary(self):
        integrand               = self.model.birth_kernel(self.ages, self.u)
        integrand_no_a0         = integrand.copy()
        integrand_no_a0[:, 0]   = 0.0
        partial_integral        = simpson(integrand_no_a0, x=self.ages, axis=1)
        self.u[:, 0]            = partial_integral + (self.da / 3.0) * integrand[:, 0]

    def step(self):
        t0 = self.t
        self._reaction_substep(self.dt / 2.0, t_start=t0)
        self._transport_substep()
        self._reaction_substep(self.dt / 2.0, t_start=t0 + self.dt / 2.0)
        self._apply_boundary()
        self.t = t0 + self.dt

    def run(self, T, callback=None):
        n_steps = int(round(T / self.dt))
        for _ in range(n_steps):
            self.step()
            if callback is not None:
                callback(self.t, self.u, self.w)
        return self.u, self.w

