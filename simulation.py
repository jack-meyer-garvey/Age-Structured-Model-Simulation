"""## Malaria"""

"""Parameter functions for the Kawakami-Zhao (2021) malaria model."""

import numpy as np

A_MAX = 90.0

# --- Demographic --------------------------------------------------------

def b_h(a, c=1.1644):
    """Birth rate. Brass form fit to Nigeria 2015 data.
    The constant c is rescaled from Kawakami's 0.4496 to give a self-consistent
    disease-free equilibrium at N_h* ~ 10^8 with the density-dependent
    mortality mu_h1 * N_h."""
    b1, b2, b3, b4 = 0.0001218, 0.3022, 78.38, 0.04006
    a = np.asarray(a, dtype=float)
    return c * b1 * np.exp(-b2 * (a - b3) - np.exp(-b4 * (a - b3)))

def mu_h0(a):
    """Age-only mortality (Heligman-Pollard form). The mu_o term diverges
    as a -> A; we cap it at a finite value so the stiffness stays bounded."""
    a = np.asarray(a, dtype=float)
    mu_c = 0.9959 * np.exp(-0.6776 * a)
    mu_m = 0.1277 * np.exp(0.09171 * (a - 66.78)
                           - np.exp(0.0006743 * (a - 66.78)))
    denom = np.maximum(A_MAX - a, 0.5)
    mu_o = 0.05859 / denom
    return mu_c + mu_m + mu_o

MU_H1 = 1.6e-10

def mu_h(a, N_h):
    return mu_h0(a) + MU_H1 * N_h

# --- Disease ------------------------------------------------------------

def rho(a):
    """Biting preference (sigmoidal in age)."""
    a = np.asarray(a, dtype=float)
    return 1.0 / (1.0 + np.exp(-(a - 4.0))) - 1.0 / (1.0 + np.exp(4.0))

def delta_h(a, c=0.006444):
    """Malaria-induced mortality (high in 0-5, ~0 elsewhere)."""
    a = np.asarray(a, dtype=float)
    return c / (1.0 + np.exp(2.0 * a - 14.0))

ZETA_H  = 1.0
GAMMA_H = 2.0

# --- Mosquito -----------------------------------------------------------

LAMBDA_V = 1.0e10
MU_V     = 13.0

# --- Transmission -------------------------------------------------------

BETA_BASELINE = 18.0
P1            = 0.5
P2            = 2.0 / 45.0

"""Kawakami-Zhao (2021) malaria model as an AgeStructuredModel.

State layout:
    u[0] = s_h(t, a)   (susceptible hosts)
    u[1] = i_h(t, a)   (infected hosts)
    u[2] = r_h(t, a)   (recovered hosts)
    w[0] = S_v(t)      (susceptible mosquitoes)
    w[1] = I_v(t)      (infected mosquitoes)
"""

import numpy as np
from scipy.integrate import trapezoid



class KawakamiMalaria(AgeStructuredModel):

    def __init__(self, beta=BETA_BASELINE,
                 s_init_total=1.0e8, i_init_frac=1.0e-3, ages_for_init=None):
        self.beta         = beta
        self.s_init_total = s_init_total
        self.i_init_frac  = i_init_frac
        self._ages_init   = ages_for_init        # optional; for IC shape

    def reaction(self, t, ages, u, w):
        s_h, i_h, r_h = u[0], u[1], u[2]
        S_v, I_v      = w[0], w[1]

        n_h          = s_h + i_h + r_h
        N_h          = trapezoid(n_h, x=ages)
        rho_vals     = rho(ages)
        rho_n_int    = trapezoid(rho_vals * n_h, x=ages)
        rho_n_int    = max(rho_n_int, 1e-30)

        lambda_vh    = P1 * self.beta * I_v * rho_vals / rho_n_int
        mu_h_L         = mu_h(ages, N_h)
        delta_h_vals = delta_h(ages)

        du = np.empty_like(u)
        du[0] = -lambda_vh * s_h + GAMMA_H * r_h - mu_h_L * s_h
        du[1] =  lambda_vh * s_h - (ZETA_H + delta_h_vals + mu_h_L) * i_h
        du[2] =  ZETA_H * i_h - (GAMMA_H + mu_h_L) * r_h
        return du

    def reaction_ode(self, t, u, w):
        s_h, i_h, r_h = u[0], u[1], u[2]
        S_v, I_v      = w[0], w[1]

        ages         = self._ages_cache
        n_h          = s_h + i_h + r_h
        rho_vals     = rho(ages)
        rho_n_int    = trapezoid(rho_vals * n_h, x=ages)
        rho_n_int    = max(rho_n_int, 1e-30)
        rho_i_int    = trapezoid(rho_vals * i_h, x=ages)

        lambda_hv    = P2 * self.beta * rho_i_int / rho_n_int

        dw = np.empty(2)
        dw[0] = LAMBDA_V - (lambda_hv + MU_V) * S_v
        dw[1] = lambda_hv * S_v - MU_V * I_v
        return dw

    def birth_kernel(self, ages, u):
        """All births enter s_h. Birth rate b_h(a) acts on total n_h."""
        n_h    = u[0] + u[1] + u[2]
        out    = np.zeros_like(u)
        out[0] = b_h(ages) * n_h
        return out

    def initial_condition(self, ages):
        """Set susceptible-only IC scaled to s_init_total, plus small i seed."""
        self._ages_cache = ages
        # Approximate susceptible age profile by survival under mu_h0.
        cumint   = np.concatenate(([0.0],
            np.cumsum(0.5*(mu_h0(ages[:-1]) + mu_h0(ages[1:])) * np.diff(ages))))
        surv     = np.exp(-cumint)
        scale    = self.s_init_total / max(trapezoid(surv, x=ages), 1e-30)
        s0       = scale * surv
        i0       = self.i_init_frac * s0

        u0 = np.zeros((3, ages.size))
        u0[0] = s0 - i0
        u0[1] = i0
        u0[2] = 0.0
        return u0

    def initial_ode(self):
        S_v0 = LAMBDA_V / MU_V
        I_v0 = self.i_init_frac * S_v0
        return np.array([S_v0, I_v0])

"""Disease-free equilibrium computation and Kawakami's R_0 formula."""

import numpy as np
from scipy.integrate import trapezoid


def compute_dfe(M, T_settle=300.0, s_init_total=1.0e8):
    """Run the disease-free model to steady state. Returns (ages, s_star, N_star, S_v_star)."""
    model  = KawakamiMalaria(beta=1.0, s_init_total=s_init_total, i_init_frac=0.0)
    solver = AgeStructuredSolver(model, A_max=A_MAX, M=M)
    solver.run(T=T_settle)
    ages    = solver.ages
    s_star  = solver.u[0]
    N_star  = float(trapezoid(s_star, x=ages))
    S_v_star = float(solver.w[0])
    return ages, s_star, N_star, S_v_star


def R0(beta, ages, s_star, N_star):
    """Evaluate Kawakami's formula

        R_0 = integral_0^A R_1(sigma) R_2(sigma) d sigma,

        R_1(sigma) = p_1 beta rho(sigma) s*(sigma) / (rho_n_int * mu_v)
        R_2(sigma) = integral_sigma^A [p_2 beta rho(a) Lambda_v / (rho_n_int mu_v)]
                        * exp(-int_sigma^a [zeta + delta + mu_h] db) da
    """
    rho_vals     = rho(ages)
    rho_n_int    = trapezoid(rho_vals * s_star, x=ages)   # n* = s* at DFE
    mu_h_star    = mu_h(ages, N_star)
    leave_rate   = ZETA_H + delta_h(ages) + mu_h_star

    # cumulative integral of leave_rate (trapezoidal)
    cum_leave    = np.concatenate(([0.0],
        np.cumsum(0.5 * (leave_rate[:-1] + leave_rate[1:]) * np.diff(ages))))

    R1 = P1 * beta * rho_vals * s_star / (rho_n_int * MU_V)

    R2_integrand = P2 * beta * rho_vals * LAMBDA_V / (rho_n_int * MU_V)
    # For each sigma, R_2(sigma) = int_sigma^A R2_integrand(a) * exp(-(cum_leave[a] - cum_leave[sigma])) da
    R2 = np.empty_like(ages)
    for i in range(len(ages)):
        kernel = R2_integrand[i:] * np.exp(-(cum_leave[i:] - cum_leave[i]))
        R2[i]  = trapezoid(kernel, x=ages[i:]) if i < len(ages) - 1 else 0.0

    return float(trapezoid(R1 * R2, x=ages))


def beta_critical(ages, s_star, N_star, beta_ref=1.0):
    """R_0 scales as beta^2, so beta* = beta_ref / sqrt(R_0(beta_ref))."""
    R0_ref = R0(beta_ref, ages, s_star, N_star)
    return beta_ref / np.sqrt(R0_ref)

